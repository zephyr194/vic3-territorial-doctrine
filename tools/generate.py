#!/usr/bin/env python3
"""Generate shared laws, IG opinions and balance values without dependencies."""
import argparse
import json
import re
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools.policy_assets import assets
from tools.development_assets import assets as development_assets
from tools.success_assets import assets as success_assets
from tools.bargaining_assets import assets as bargaining_assets
from tools.civic_assets import assets as civic_assets
from tools.law_text import doctrine_description, group_description
from territorial_doctrine.model import RULES, DOCTRINES  # noqa: E402

HEADER = "# Generated by tools/generate.py from territorial_doctrine/rules.json.\n"


def icon(index: int) -> bytes:
    """A small original DDS emblem; no dependency on vanilla image paths."""
    size = 64
    colors = [(94, 131, 111), (168, 139, 82), (88, 129, 164), (153, 87, 81)]
    color = colors[index]
    pixels = bytearray()
    for y in range(size):
        for x in range(size):
            edge = 3 <= x <= 60 and 3 <= y <= 60 and (x < 6 or x > 57 or y < 6 or y > 57)
            pole = 17 <= x <= 20 and 14 <= y <= 50
            flag = 21 <= x <= 47 and 14 <= y <= 32
            stripe = flag and (y - 14) // 5 <= index
            r, g, b = (225, 215, 185) if edge or pole else color if stripe else (34, 38, 44)
            pixels.extend((r, g, b, 255))
    # DDS_HEADER, uncompressed RGBA, pitch = width * 4.
    header = struct.pack('<7I11I8I5I', 124, 0x100F, size, size, size * 4, 0, 0,
                         *([0] * 11), 32, 0x41, 0, 32,
                         0xFF, 0xFF00, 0xFF0000, 0xFF000000,
                         0x1000, 0, 0, 0, 0)
    return b'DDS ' + header + pixels


def outputs() -> dict[Path, bytes]:
    out: dict[Path, bytes] = {}

    def put(path: str, data: str | bytes):
        if path.endswith('.yml') and isinstance(data, str):
            data = re.sub(r'^(\s+[\w.]+:\d+\s+")(?!(?:VTD ))', r'\1VTD ', data, flags=re.M)
        encoding = 'utf-8' if path.endswith('.json') else 'utf-8-sig'
        out[ROOT / 'mod' / path] = data.encode(encoding) if isinstance(data, str) else data

    put('common/law_groups/td_law_group.txt', HEADER + '''lawgroup_territorial_doctrine = {
    law_group_category = power_structure
    base_enactment_days = 90
    enable = { td_feature_enabled_trigger = yes }
    change_allowed_trigger = {
        td_can_legislate_trigger = yes
    }
}
''')
    laws = HEADER
    ideologies = HEADER
    scores = HEADER + 'td_base_scores_effect = {\n    every_interest_group = { set_variable = { name = td_score value = 0 } }\n'
    opinion = {-2: 'strongly_disapprove', -1: 'disapprove', 0: 'neutral',
               1: 'approve', 2: 'strongly_approve'}
    for i, doctrine in enumerate(DOCTRINES):
        image = f'gfx/interface/icons/td/{doctrine}.dds'
        put(image, icon(i))
        data = RULES['doctrines'][doctrine]
        effects = {f'interest_group_ig_{group}_pol_str_mult': value
                   for group, value in data['political_strength'].items()}
        effects.update(data['country_modifiers'])
        modifier = '\n'.join(f'        {key} = {value}' for key, value in effects.items())
        laws += f'''law_td_{doctrine} = {{
    group = lawgroup_territorial_doctrine
    icon = "{image}"
    progressiveness = 0
    modifier = {{
{modifier}
    }}
    can_enact = {{ td_can_legislate_trigger = yes }}
    on_enact = {{ td_doctrine_changed_effect = yes }}
    ai_enact_weight_modifier = {{ value = 1 }}
}}
'''
    for group, opinions in RULES['groups'].items():
        ideologies += f'ideology_td_{group} = {{\n    icon = "gfx/interface/icons/td/strategic_frontiers.dds"\n    lawgroup_territorial_doctrine = {{\n'
        for doctrine, value in zip(DOCTRINES, opinions):
            ideologies += f'        law_td_{doctrine} = {opinion[value]}\n'
        ideologies += '    }\n}\n'
        scores += f'    ig:ig_{group} = {{\n'
        for doctrine, value in zip(DOCTRINES, opinions):
            scores += f'''        if = {{
            limit = {{ owner = {{ has_law = law_type:law_td_{doctrine} }} }}
            set_variable = {{ name = td_score value = {value * 10} }}
        }}
'''
        scores += '    }\n'
    scores += '}\n'
    put('common/laws/td_laws.txt', laws)
    put('common/ideologies/td_ideologies.txt', ideologies)
    put('common/scripted_effects/td_base_scores.txt', scores)
    values = HEADER
    for doctrine, data in RULES['doctrines'].items():
        values += f'td_{doctrine}_multiplier = {data["cost_multiplier"]}\n'
    for key, value in RULES['bill'].items():
        values += f'td_bill_{key} = {value}\n'
    values += f'td_integration_months = {RULES["integration"]["months"]}\ntd_annual_cost_multiplier = {RULES["integration"]["annual_cost_multiplier"]}\ntd_cost_precision = {RULES["integration"]["cost_precision"]}\n'
    put('common/script_values/td_constants.txt', values)
    policy = HEADER
    policy += '''td_power_category = {
    value = 0
    if = { limit = { OR = { has_law = law_type:law_autocracy has_law = law_type:law_single_party_state } } value = 1 }
    else_if = { limit = { OR = { has_law = law_type:law_census_suffrage has_law = law_type:law_universal_suffrage } } value = 2 }
}
td_government_category = {
    value = 0
    if = { limit = { has_law = law_type:law_monarchy } value = 1 }
    else_if = { limit = { OR = { has_law = law_type:law_presidential_republic has_law = law_type:law_parliamentary_republic } } value = 2 }
}
'''
    policy += 'td_reason_bonus = {\n    value = 0\n'
    for reason in RULES['reasons'].values():
        policy += f'    if = {{ limit = {{ var:td_reason = {reason["id"]} }}\n'
        for category, mapping in (('government', {'other': 0, 'monarchy': 1, 'republic': 2}), ('power', {'other': 0, 'autocracy': 1, 'democracy': 2})):
            for name, index in mapping.items():
                bonus = reason[category][name]
                if bonus:
                    policy += f'        if = {{ limit = {{ td_{category}_category = {index} }} add = {bonus} }}\n'
        policy += '    }\n'
    policy += '}\ntd_reason_cost_multiplier = {\n    value = 1\n'
    for reason in RULES['reasons'].values():
        policy += f'    if = {{ limit = {{ var:td_reason = {reason["id"]} }} value = {reason["cost_multiplier"]} }}\n'
    policy += '}\ntd_actor_cost_multiplier = {\n    value = 1\n'
    for regime in RULES['regimes'].values():
        policy += f'    if = {{ limit = {{ td_power_category = {regime["id"]} }} value = {regime["actor_administration_multiplier"]} }}\n'
    policy += '}\n'
    policy += 'td_infamy_policy_multiplier = {\n    value = 1\n'
    for doctrine, info in RULES['doctrines'].items():
        factor = 1 + info['country_modifiers'].get('country_infamy_generation_mult', 0)
        policy += f'    if = {{ limit = {{ has_law = law_type:law_td_{doctrine} }} value = {factor} }}\n'
    policy += '}\n'
    put('common/script_values/td_policy_values.txt', policy)
    cache = HEADER + '''# Country scope with PREV = state. Store literal values so extinct former
# owners do not erase the institutional cost of territory they lost.
td_store_power_on_prev_state_effect = {
'''
    for regime in RULES['regimes'].values():
        cache += f'''    if = {{
        limit = {{ td_power_category = {regime['id']} }}
        prev = {{
            set_variable = {{ name = td_live_power value = {regime['id']} }}
            set_variable = {{ name = td_live_diplomatic value = {regime['diplomatic_multiplier']} }}
            set_variable = {{ name = td_live_administration value = {regime['inherited_administration_multiplier']} }}
        }}
    }}
'''
    cache += '}\n'
    put('common/scripted_effects/td_regime_cache.txt', cache)
    modifiers = HEADER
    for doctrine, data in RULES['doctrines'].items():
        if data['focus_limit']:
            modifiers += f'''td_focus_{doctrine} = {{
    country_bureaucracy_add = -{data['bureaucracy']}
    country_authority_add = -{data['authority']}
}}
'''
    modifiers += f'''td_project_cost = {{ country_bureaucracy_add = -1 }}
td_pledge_fulfilled = {{ interest_group_approval_add = {RULES['negotiation']['fulfilled_approval']} }}
td_pledge_broken = {{ interest_group_approval_add = {RULES['negotiation']['broken_approval']} }}
td_requires_admission = {{ state_disallow_incorporation = yes }}
'''
    modifiers += 'td_admission_ratified = {} # Legal record; all economic incentives belong to new territory.\n'
    modifiers += 'td_annual_integration = { state_disallow_incorporation = yes }\n'
    put('common/static_modifiers/td_modifiers.txt', modifiers)
    for language, label in [('english', 'en'), ('simp_chinese', 'zh')]:
        loc = f'l_{language}:\n'
        loc += ' lawgroup_territorial_doctrine:0 "' + ('国家领土原则' if label == 'zh' else 'National Territorial Doctrine') + '"\n'
        loc += ' lawgroup_territorial_doctrine_desc:0 "' + ('确立国家守成、恢复法理疆界、保障战略边疆或建立帝国的长期方向。不同原则提供理由与集团偏好的背景，具体利益与付费承诺在逐目标国内审议中处理。' if label == 'zh' else 'Choose a lasting policy of restraint, lawful restoration, strategic frontiers or imperial expansion. Each doctrine frames arguments and group preferences; actual interests and funded commitments are negotiated in individual bills.') + '"\n'
        for doctrine, data in RULES['doctrines'].items():
            title = data[label]
            desc = json.dumps(doctrine_description(doctrine, label), ensure_ascii=False)
            loc += f' law_td_{doctrine}:0 "{title}"\n law_td_{doctrine}_desc:0 {desc}\n'
            if data['focus_limit']:
                loc += f' td_focus_{doctrine}:0 "{title} — ' + ('重点区域预留' if label == 'zh' else 'Focus Region Commitments') + '"\n'
            loc += f' td_territory_{doctrine}:0 "{title} — ' + ('领土开发' if label == 'zh' else 'Territorial Development') + '"\n'
            if RULES['territorial_success']['acquisition_legitimacy'][doctrine]:
                loc += f' td_success_{doctrine}:0 "{title} — ' + ('领土成果合法性' if label == 'zh' else 'Territorial Success Legitimacy') + '"\n'
        loc += ' td_success_admission:0 "' + ('完成逐州接纳的政治信誉' if label == 'zh' else 'Political Credit for Completed State Admission') + '"\n'
        for group in RULES['groups']:
            name = RULES['group_politics'][group][label]
            loc += f' ideology_td_{group}:0 "' + (f'{name}的领土立场' if label == 'zh' else f'{name} Territorial Position') + '"\n'
            loc += f' ideology_td_{group}_desc:0 ' + json.dumps(group_description(group, label), ensure_ascii=False) + '\n'
        put(f'localization/{language}/td_laws_l_{language}.yml', loc)
    metadata = {
        'name': 'Territorial Doctrine',
        'id': 'territorial_doctrine', 'version': RULES['version'],
        'game_id': 'victoria3', 'supported_game_version': '1.13.*',
        'short_description': 'VTD: domestic territorial bargaining, budgets and accountable commitments',
        'tags': ['Gameplay', 'Politics'], 'relationships': [],
        'game_custom_data': {'multiplayer_synchronized': True}
    }
    put('.metadata/metadata.json', json.dumps(metadata, ensure_ascii=False, indent=2) + '\n')
    for path, content in assets().items():
        put(path, content)
    for path, content in development_assets().items():
        put(path, content)
    for path, content in success_assets().items():
        put(path, content)
    for path, content in bargaining_assets().items():
        put(path, content)
    for path, content in civic_assets().items():
        put(path, content)
    # Prefix hand-maintained catalogs too, keeping regeneration idempotent.
    for language in RULES['localization']['translated']:
        for path in (ROOT / 'mod/localization' / language).glob('*.yml'):
            if path not in out:
                put(str(path.relative_to(ROOT / 'mod')), path.read_text(encoding='utf-8-sig'))
    # English is the source fallback; other game languages use identical keys/text
    # until a native translation is supplied. Never alter the game's language setting.
    english = {p.name: content.decode('utf-8-sig') for p, content in out.items()
               if p.parent.name == 'english' and p.suffix == '.yml'}
    for p in (ROOT / 'mod/localization/english').glob('*.yml'):
        english.setdefault(p.name, p.read_text(encoding='utf-8-sig'))
    for lang in RULES['localization']['languages']:
        if lang in RULES['localization']['translated']:
            continue
        for filename, content in english.items():
            put(f'localization/{lang}/{filename.replace("_l_english", "_l_"+lang)}',
                content.replace('l_english:', f'l_{lang}:', 1))
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated assets are stale')
    args = parser.parse_args()
    stale = []
    for path, data in outputs().items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if stale:
        print('Stale generated files:\n' + '\n'.join(stale), file=sys.stderr)
        return 1
    print('Generated assets are current.' if args.check else 'Generated laws, opinions, balance constants, localization and icons.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
