"""State-scoped doctrine incentives; ownership never grants foreign-state buffs."""
from territorial_doctrine.model import RULES

HEADER = '# Generated by tools/generate.py from territorial_doctrine/rules.json.\n'


def assets():
    modifiers = HEADER
    cleanup = 'td_clear_state_development_effect = {\n'
    refresh = '''td_refresh_state_development_effect = {
    if = {
        limit = { td_feature_enabled_trigger = yes td_development_target_trigger = yes owner = { td_has_doctrine_trigger = yes } }
        owner = {
'''
    for index, (doctrine, info) in enumerate(RULES['doctrines'].items(), 1):
        modifiers += f'td_territory_{doctrine} = {{\n'
        modifiers += ''.join(f'    {key} = {value}\n' for key, value in info['territory_modifiers'].items())
        modifiers += '}\n'
        cleanup += f'    remove_modifier = td_territory_{doctrine}\n'
        refresh += f'            if = {{ limit = {{ has_law = law_type:law_td_{doctrine} }} prev = {{ set_variable = {{ name = td_desired_development value = {index} }} }} }}\n'
    cleanup += '    remove_variable = td_development_profile\n    remove_variable = td_development_owner\n}\n'
    refresh += '''        }
        if = {
            limit = { OR = { NOT = { has_variable = td_development_profile } NOT = { var:td_development_profile = var:td_desired_development } NOT = { var:td_development_owner = owner } } }
            td_clear_state_development_effect = yes
'''
    for index, doctrine in enumerate(RULES['doctrines'], 1):
        refresh += f'            if = {{ limit = {{ var:td_desired_development = {index} }} add_modifier = td_territory_{doctrine} }}\n'
    refresh += '''            set_variable = { name = td_development_profile value = var:td_desired_development }
            set_variable = { name = td_development_owner value = owner }
        }
        remove_variable = td_desired_development
    }
    else = { td_clear_state_development_effect = yes }
}
'''
    return {'common/static_modifiers/td_territory_modifiers.txt': modifiers,
            'common/scripted_effects/td_development.txt': HEADER + cleanup + refresh}
