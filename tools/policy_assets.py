"""Generated colonial values and IG law positions, shared with the model."""
from territorial_doctrine.model import RULES, doctrine_scores, political_weight
from tools.law_text import group_description
import json

HEADER = '# Generated by tools/generate.py from territorial_doctrine/rules.json.\n'


def assets():
    out = {}
    c = RULES['colonial']
    values = HEADER + 'td_colonial_category = {\n    value = 0\n'
    for p in c['policies'].values():
        if 'law' in p:
            values += f'    if = {{ limit = {{ has_law = law_type:{p["law"]} }} value = {p["id"]} }}\n'
    values += '}\ntd_humanitarian_stage = {\n    value = 0\n'
    for tech in c['humanitarian_technologies']:
        values += f'    if = {{ limit = {{ has_technology_researched = {tech} }} add = 1 }}\n'
    values += '}\ntd_colonial_profile = { value = td_colonial_category multiply = 3 add = td_humanitarian_stage }\n'
    for name, field in [('expansion_pull', 'expansion'), ('admission_pull', 'admission'), ('base_cost', 'cost_multiplier')]:
        values += f'td_colonial_{name} = {{\n    value = {1 if field == "cost_multiplier" else 0}\n'
        for p in c['policies'].values():
            values += f'    if = {{ limit = {{ td_colonial_category = {p["id"]} }} value = {p[field]} }}\n'
        if field != 'cost_multiplier':
            op = 'subtract' if field == 'expansion' else 'add'
            values += f'    {op} = {{ value = td_humanitarian_stage multiply = {c["stage_shift"]} }}\n'
        values += '}\n'
    values += f'''td_colonial_admission_multiplier = {{
    value = td_colonial_base_cost
    multiply = {{ value = td_humanitarian_stage multiply = {c['rights_cost_per_stage']} add = 1 }}
}}
td_focus_limit = {{
    value = 0
'''
    for d, info in RULES['doctrines'].items():
        values += f'    if = {{ limit = {{ has_law = law_type:law_td_{d} }} value = {info["focus_limit"]} }}\n'
    values += '}\n'
    values += f'td_war_monthly_exhaustion = {RULES["war"]["monthly_exhaustion"]}\ntd_war_exhaustion_cap = {RULES["war"]["exhaustion_cap"]}\n'
    values += 'td_war_next_exhaustion = { value = td_war_exhaustion_cap subtract = var:td_extra_exhaustion min = td_war_monthly_exhaustion max = 0 }\n'
    out['common/script_values/td_colonial_values.txt'] = values
    ideologies = HEADER
    refresh = HEADER + '''td_refresh_colonial_profile_effect = {
    set_variable = { name = td_profile value = td_colonial_profile }
    set_variable = { name = td_humanitarian_level value = td_humanitarian_stage }
    set_variable = { name = td_expansion_pull value = td_colonial_expansion_pull }
    set_variable = { name = td_admission_pull value = td_colonial_admission_pull }
    every_interest_group = {
        if = {
            limit = { OR = { NOT = { has_variable = td_profile } NOT = { var:td_profile = owner.var:td_profile } } }
'''
    cleanup = HEADER + 'td_remove_territorial_ideologies_effect = {\n    every_interest_group = {\n'
    opinion = {-2:'strongly_disapprove', -1:'disapprove', 0:'neutral', 1:'approve', 2:'strongly_approve'}
    names = []
    for group in RULES['groups']:
        refresh += f'            if = {{ limit = {{ is_interest_group_type = ig_{group} }}\n'
        group_names = [f'ideology_td_{group}']
        for policy, p in c['policies'].items():
            for stage in range(3):
                key = f'ideology_td_p{p["id"]}_h{stage}_{group}'
                group_names.append(key); names.append((key, group, policy, stage))
                ideologies += f'{key} = {{\n    icon = "gfx/interface/icons/td/strategic_frontiers.dds"\n    lawgroup_territorial_doctrine = {{\n'
                for d in RULES['doctrines']:
                    level = int(political_weight(doctrine_scores(d, policy, stage)[group]) * 2)
                    ideologies += f'        law_td_{d} = {opinion[level]}\n'
                ideologies += '    }\n}\n'
        for key in group_names:
            removal = f'if = {{ limit = {{ has_ideology = ideology:{key} }} remove_ideology = {key} }}'
            refresh += f'                {removal}\n'; cleanup += f'        {removal}\n'
        for p in c['policies'].values():
            for stage in range(3):
                key = f'ideology_td_p{p["id"]}_h{stage}_{group}'
                refresh += f'                if = {{ limit = {{ owner = {{ var:td_profile = {p["id"]*3+stage} }} }} add_ideology = {key} }}\n'
        refresh += '            }\n'
    refresh += '            set_variable = { name = td_profile value = owner.var:td_profile }\n        }\n    }\n}\n'
    cleanup += '        remove_variable = td_profile\n    }\n}\n'
    out['common/ideologies/td_colonial_ideologies.txt'] = ideologies
    out['common/scripted_effects/td_colonial_profiles.txt'] = refresh + cleanup
    bill = HEADER + '''td_colonial_bill_scores_effect = {
    td_refresh_colonial_profile_effect = yes
    if = {
        limit = { exists = var:td_target var:td_target = { td_colonial_target_trigger = yes } OR = { var:td_bill = 1 var:td_bill = 2 } }
'''
    for group, weight in c['weights'].items():
        bill += f'''        ig:ig_{group} = {{
            if = {{ limit = {{ owner = {{ var:td_bill = 1 }} }} change_variable = {{ name = td_score add = {{ value = owner.td_colonial_expansion_pull multiply = {weight} }} }} }}
            else = {{ change_variable = {{ name = td_score add = {{ value = owner.td_colonial_admission_pull multiply = {weight} }} }} }}
        }}
'''
    bill += '    }\n}\n'
    out['common/scripted_effects/td_colonial_scores.txt'] = bill
    for lang in ('english','simp_chinese'):
        label = 'zh' if lang == 'simp_chinese' else 'en'
        loc = f'l_{lang}:\n'
        for key, group, policy, stage in names:
            name = RULES['group_politics'][group][label]
            title = f'{name}的领土立场' if label == 'zh' else f'{name} Territorial Position'
            desc = json.dumps(group_description(group, label, policy, stage), ensure_ascii=False)
            loc += f' {key}:0 "{title}"\n {key}_desc:0 {desc}\n'
        out[f'localization/{lang}/td_policies_l_{lang}.yml'] = loc
    return out
